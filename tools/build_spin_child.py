"""Generate `sustained_game_spin_child.py` from the frozen g61 child, changing one wait.

The frozen child loop ends every iteration with `time.sleep(.001)`.  The spin candidate must
be *the same loop* with a different wait, so this generator copies the function text verbatim
and replaces exactly that one call with `wait(game)`.  `test_sustained_game_spin_child.py`
re-parses both functions and asserts the only difference is that call, so the copy cannot drift
silently.  Run it only when the frozen child changes (which it must not).
"""
import ast, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tools/run_sustained_game_g61.py'
TARGET = ROOT / 'tools/sustained_game_spin_child.py'
BEGIN = 'def child('
END = '    return 0 if game_child_passed(report) else 1'

HEADER = '''"""Candidate child loop: frozen g61 loop with the final wait replaced by a spin (generated).

Generated by `tools/build_spin_child.py` from `tools/run_sustained_game_g61.py`; do not edit by
hand.  The only textual difference is `wait(game)` in place of `time.sleep(.001)`.  `wait()`
sleeps as before until the pending deadline is within SPIN_MARGIN, then spins the remaining
2 ms so the 8 ms grid no longer depends on an OS wake.  Enable with FLYDIGI_SPIN_WAIT=1; with
the variable unset the loop is byte-for-byte the frozen behaviour.
"""
import importlib.util,json,os,pathlib,queue,sys,threading,time

from sustained_game_policy_current import (ROOT, build_game_plan, digest, game_child_passed,
                                           game_parent_passed, validate_game_plan, GameSession)

WORK=ROOT/'handoff/2026-10-22/work';PRIVATE=WORK/'private';sys.path.insert(0,str(WORK))

SPIN_MARGIN=0.002
_stats=dict(enabled=False,spins=0,spin_seconds=0.0,maximum_spin_seconds=0.0)


def wait(game):
    """Product wait, plus an optional spin over the last SPIN_MARGIN before the deadline."""
    if os.environ.get('FLYDIGI_SPIN_WAIT')!='1':
        time.sleep(.001);return
    target=getattr(game,'target',None)
    if target is None:
        time.sleep(.001);return
    remaining=target-time.perf_counter()
    if 0<remaining<=SPIN_MARGIN:
        began=time.perf_counter()
        while time.perf_counter()<target:pass
        elapsed=time.perf_counter()-began
        _stats.update(enabled=True,spins=_stats['spins']+1,spin_seconds=_stats['spin_seconds']+elapsed,
                      maximum_spin_seconds=max(_stats['maximum_spin_seconds'],elapsed))
        return
    time.sleep(.001)


def spin_stats():
    return dict(_stats)


'''

FOOTER = '''

def main():
    from run_sustained_game_g61 import main as base_main
    return base_main()


if __name__=='__main__':raise SystemExit(main())
'''


def child_source(text):
    start = text.index(BEGIN)
    end = text.index(END, start) + len(END)
    return text[start:end]


def build():
    text = SOURCE.read_text(encoding='utf-8')
    function = child_source(text)
    if function.count('time.sleep(.001)') != 1:
        raise SystemExit('frozen child must contain exactly one final sleep')
    function = function.replace('time.sleep(.001)', 'wait(game)')
    ast.parse(function)
    return HEADER + function + FOOTER


def main():
    body = build()
    TARGET.write_text(body, encoding='utf-8')
    print('WROTE', TARGET, len(body), 'bytes')
    module = ast.parse(body)
    functions = {n.name for n in module.body if isinstance(n, ast.FunctionDef)}
    print('FUNCTIONS', sorted(functions))


if __name__ == '__main__':
    main()
